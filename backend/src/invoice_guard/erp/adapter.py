from datetime import date
from typing import Any, Protocol
from uuid import UUID


class ERPAdapter(Protocol):
    async def find_by_external_ref(self, entity_id: str, ext_ref: UUID) -> Any | None: ...
    async def post_invoice(self, invoice: Any, ext_ref: UUID) -> Any: ...
    async def get_vendor(self, entity_id: str, supplier_key: str) -> Any | None: ...
    async def get_po(self, entity_id: str, po_number: str) -> Any | None: ...
    async def get_items(self, entity_id: str, codes: list[str]) -> dict[str, Any]: ...
    async def is_period_open(self, entity_id: str, on: date) -> bool: ...
